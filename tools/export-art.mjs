// Export the code-drawn art to PNGs in art/, and rebuild art/manifest.js.
//
//   node tools/export-art.mjs              write PNGs for keys that have no PNG yet, then rebuild the manifest
//   node tools/export-art.mjs --force icons/ironJian tiles/   also redraw these keys (or key prefixes), overwriting
//   node tools/export-art.mjs --manifest   only rebuild the manifest (after adding or deleting PNGs by hand)
//   node tools/export-art.mjs --list       print every key the game knows about
//
// Existing PNGs are never overwritten unless named in --force, so hand-edited art is safe.
// Needs Node and Playwright:  npm i -D playwright && npx playwright install chromium
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const { chromium } = createRequire(import.meta.url)('playwright'); // require, so a global install (NODE_PATH) works too

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ART = path.join(ROOT, 'art');
const args = process.argv.slice(2);
const force = args.includes('--force') ? args.slice(args.indexOf('--force') + 1).filter(a => !a.startsWith('--')) : [];
const onlyManifest = args.includes('--manifest'), listOnly = args.includes('--list');

function pngsOnDisk(dir = ART, base = '') {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e =>
    e.isDirectory() ? pngsOnDisk(path.join(dir, e.name), base + e.name + '/')
      : e.name.endsWith('.png') ? [base + e.name.slice(0, -4)] : []);
}
function writeManifest() {
  const keys = pngsOnDisk().sort();
  fs.writeFileSync(path.join(ART, 'manifest.js'),
    '/* Generated by tools/export-art.mjs: the art keys that have a PNG in this folder. Rebuild it with --manifest after adding or removing PNGs. */\n' +
    'const ART_FILES=' + JSON.stringify(keys, null, 0).replace(/","/g, '",\n"') + ';\n');
  console.log(`manifest: ${keys.length} PNGs`);
}

if (onlyManifest) { writeManifest(); process.exit(0); }

const browser = await chromium.launch();
const page = await browser.newPage();
await page.route('**/music/**', r => r.abort());
await page.goto(pathToFileURL(path.join(ROOT, 'index.html')).href + '?codeart');
await page.waitForTimeout(500);
// call every parametrised art function once per value, so each key registers in ART_GEN
const keys = await page.evaluate(() => {
  const each = (o, f) => Object.keys(o).forEach(k => { try { f(k) } catch (_) {} });
  each(IT, k => { if (!k.includes('~')) iconArt(k) });
  each(TAGS, tagArt); each(RELICS, relicArt); each(MEALS, mealArt); each(WOES, woeArt);
  [mugArt, tavernArt, counterArt, musterArt, flagArt, sageRoomArt, sageTableArt, sageBallArt, mapIconArt, coinArt,
   swordsArt, eliteArt, campArt, chestArt, eventArt, titleCrystalArt, cageBarsArt, boulderArt, shipSideArt, shipWingArt,
   () => shipArt(0), () => shipArt(1), () => BIG.crystal({}, false), () => BIG.crystal({}, true)].forEach(f => { try { f() } catch (_) {} });
  return Object.keys(ART_GEN).sort();
});
if (listOnly) { console.log(keys.join('\n')); await browser.close(); process.exit(0); }

const have = new Set(pngsOnDisk());
const want = keys.filter(k => !have.has(k) || force.some(f => k === f || (f.endsWith('/') && k.startsWith(f))));
let n = 0;
for (const k of want) {
  const url = await page.evaluate(k => ART_GEN[k](), k);
  if (!url || !url.startsWith('data:image/png;base64,')) { console.warn('skipped', k); continue; }
  const file = path.join(ART, k + '.png');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, Buffer.from(url.split(',')[1], 'base64'));
  n++;
}
await browser.close();
console.log(`wrote ${n} PNGs (${keys.length} keys, ${have.size} already had a PNG)`);
writeManifest();
